for (const type of ['click', 'input', 'focusin']) {
  document.addEventListener(type, event => {
    const name = type === 'focusin' ? 'focus' : type;
    let el = event.target;
    while (el && el !== document) {
      const id = el.getAttribute('data-ev-' + name);
      if (id !== null) {
        const params = JSON.parse(el.getAttribute('data-args-' + name) || '[]');
        studioActions[id]?.(event, el, params);
        if (event.cancelBubble) break;
      }
      el = el.parentElement;
    }
  });
}
