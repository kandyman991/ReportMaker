"""Pure M6.5 metadata/boilerplate translation primitives (pre-schema gate).

This module deliberately has NO project-format, Qt, browser or export side
effects. It establishes a typed semantic-key/source-provenance contract that
can be reviewed independently before a v5 project migration is authorized.
An approved entry is transient until project persistence is reviewed.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
from re import fullmatch
from types import MappingProxyType

from ..model import NestedModuleBlock, PageBreakBlock, Report, validate_language_tag


# These strings are generated by ReportMaker, NOT translations of a
# Report.primary_language source. Their immutable reference language is en.
_ENGLISH = {
    "heading.report_information": "Report information",
    "heading.summary": "Summary",
    "heading.report_content": "Report content",
    "label.page": "Page",
    # Preview-only report content: each generated phrase must be localized.
    "preview.summary_detail": "derived from the report hierarchy",
    "preview.manual_page_break": "Manual page break in exported document",
    "preview.footer_prefix": "Footer",
    "field.created": "Created",
    "field.intervention_from": "Intervention from",
    "field.intervention_to": "Intervention to",
    "field.customer": "Customer",
    "field.site": "Site",
    "field.machine": "Machine",
    "field.machine_serial": "Machine serial",
    "field.ticket": "Ticket",
    "field.personnel": "Personnel",
    "field.intervention_types": "Intervention types",
    "field.other_intervention_details": "Other intervention details",
    "intervention.supervision": "Supervision",
    "intervention.ordinary_maintenance": "Ordinary maintenance",
    "intervention.extraordinary_maintenance": "Extraordinary maintenance",
    "intervention.other": "Other",
}
ENGLISH_LABELS = MappingProxyType(_ENGLISH)
FREE_TEXT_KEYS = frozenset({
    "metadata.other_intervention_detail",
    "branding.footer_note",
})
ALL_KEYS = frozenset(_ENGLISH) | FREE_TEXT_KEYS
MAX_ENTRIES = 4096
MAX_FREE_TEXT = 10_000
MAX_LABEL = 320


def _xml_safe_text(text: object, limit: int) -> bool:
    """Reject XML 1.0-illegal characters before approval or replay.

    DOCX is XML and ReportLab also consumes customer-facing text. Keep this
    check in the pure boundary so corrupt translations never reach either.
    """
    if not isinstance(text, str) or len(text) > limit:
        return False
    return all(ord(char) in (0x09, 0x0A, 0x0D) or
               0x20 <= ord(char) <= 0xD7FF or
               0xE000 <= ord(char) <= 0xFFFD or
               0x10000 <= ord(char) <= 0x10FFFF
               for char in text)


class MetadataTranslationRequiredError(ValueError):
    """Export-language metadata would be missing, stale or ambiguous."""


@dataclass(frozen=True)
class LocaleApproval:
    """One reviewed translation of a semantic source at one source revision."""

    key: str
    language: str
    text: str
    source_sha256: str


def source_digest(key: str, source_language: str, source: str) -> str:
    """Bind translation approval to its semantic field and exact original."""
    if not isinstance(key, str) or key not in ALL_KEYS or not _xml_safe_text(source, len(source)):
        raise ValueError("Unknown metadata localization source")
    validate_language_tag(source_language)
    # Prefix length avoids concatenation ambiguity even if a field has a null.
    payload = "|".join((str(len(key)), key, str(len(source_language)),
                        source_language.casefold(), str(len(source)), source))
    return sha256(payload.encode("utf-8")).hexdigest()


class MetadataLocale:
    """Fail-closed, read-only resolver; no project mutation or persistence."""

    def __init__(self, report: Report, approvals=(), *, footer_note: str = "",
                 footer_source_language: str | None = None):
        if not isinstance(report, Report):
            raise ValueError("Expected canonical report")
        if not _xml_safe_text(footer_note, MAX_FREE_TEXT):
            raise ValueError("Invalid branding footer text")
        # Template-branding prose need not share the report writing language.
        # Requiring its declared source locale prevents false approvals.
        if footer_note and footer_source_language is None:
            raise ValueError("Branded footer prose requires an explicit source language")
        if footer_source_language is not None:
            validate_language_tag(footer_source_language)
        if not isinstance(approvals, (tuple, list)) or len(approvals) > MAX_ENTRIES:
            raise ValueError("Invalid number of metadata localization entries")
        self._report = report
        self._footer_note = footer_note
        self._footer_source_language = footer_source_language
        self._records = {}
        for approval in approvals:
            if not isinstance(approval, LocaleApproval):
                raise ValueError("Invalid localization approval record")
            key = approval.key
            if not isinstance(key, str) or key not in ALL_KEYS:
                raise ValueError("Unknown semantic localization key")
            validate_language_tag(approval.language)
            if not _xml_safe_text(approval.text, MAX_FREE_TEXT if key in FREE_TEXT_KEYS
                                  else MAX_LABEL):
                raise ValueError("Invalid localized text length")
            if not isinstance(approval.source_sha256, str) or not fullmatch(
                    r"[0-9a-f]{64}", approval.source_sha256):
                raise ValueError("Malformed source provenance digest")
            # Do not accept a stored translation that claims to replace the
            # canonical original; stale entries are allowed for later review.
            _, source_language = self.source(key)
            if approval.language.casefold() == source_language.casefold():
                raise ValueError("Source-language text must stay canonical")
            identifier = (key, approval.language.casefold())
            if identifier in self._records:
                raise ValueError("Duplicate localization language (case-insensitive)")
            self._records[identifier] = approval

    def source(self, key: str) -> tuple[str, str]:
        """(exact source text, source language) for an allowlisted field."""
        if not isinstance(key, str):
            raise ValueError("Unknown semantic localization key")
        if key in ENGLISH_LABELS:
            return ENGLISH_LABELS[key], "en"
        if key == "metadata.other_intervention_detail":
            return self._report.other_intervention_detail, self._report.primary_language
        if key == "branding.footer_note":
            return self._footer_note, (self._footer_source_language or
                                       self._report.primary_language)
        raise ValueError("Unknown semantic localization key")

    def approve(self, key: str, language: str, text: str) -> LocaleApproval:
        """Build a reviewable record; never commit it to a project on its own."""
        validate_language_tag(language)
        original, source_language = self.source(key)
        if language.casefold() == source_language.casefold():
            raise ValueError("Cannot translate over canonical source")
        if (not _xml_safe_text(text, MAX_FREE_TEXT if key in FREE_TEXT_KEYS
                               else MAX_LABEL) or
                original.strip() and not text.strip()):
            raise ValueError("A nonempty source requires bounded, nonblank translation")
        if key in FREE_TEXT_KEYS and not original.strip():
            raise ValueError("Cannot invent a translated metadata value without source")
        return LocaleApproval(key, language, text,
                              source_digest(key, source_language, original))

    def resolve(self, key: str, language: str) -> str:
        """Strict customer export selection; never silently use another locale."""
        validate_language_tag(language)
        original, source_language = self.source(key)
        if language.casefold() == source_language.casefold():
            return original
        approval = self._records.get((key, language.casefold()))
        if approval is None:
            if not original.strip():
                return ""
            raise MetadataTranslationRequiredError(
                f"Missing {language} metadata translation: {key}")
        digest = source_digest(key, source_language, original)
        if key in FREE_TEXT_KEYS and not original.strip():
            if approval.source_sha256 == digest and approval.text.strip():
                raise MetadataTranslationRequiredError(
                    f"Fabricated {language} metadata translation: {key}")
            return ""
        if approval.source_sha256 != digest:
            raise MetadataTranslationRequiredError(
                f"Outdated {language} metadata translation: {key}")
        if original.strip() and not approval.text.strip():
            raise MetadataTranslationRequiredError(
                f"Blank {language} metadata translation: {key}")
        return approval.text

    def resolve_many(self, keys, language: str) -> dict[str, str]:
        """Resolve all required labels before a destination can be written."""
        if not isinstance(keys, (tuple, list)) or any(
                not isinstance(key, str) or key not in ALL_KEYS for key in keys):
            raise ValueError("Invalid localization key sequence")
        return {key: self.resolve(key, language) for key in keys}


def visible_metadata_keys(report: Report, *, preview: bool = False,
                          footer_note: str = "") -> tuple[str, ...]:
    """Semantic keys actually shown by the current export metadata layout.

    This function intentionally derives display presence from the canonical
    report instead of keeping an independent list of report metadata facts.
    """
    if not isinstance(report, Report):
        raise ValueError("Expected canonical report")
    if not isinstance(footer_note, str):
        raise ValueError("Invalid branding footer text")
    snapshot = report.customer_snapshot
    labels = [
        "heading.report_information", "heading.summary", "label.page",
        "field.created", "field.intervention_from", "field.intervention_to",
    ]
    for key, value in (
        ("field.customer", snapshot.customer_name if snapshot else ""),
        ("field.site", snapshot.site_name if snapshot else ""),
        ("field.machine", snapshot.machine_name if snapshot else ""),
        ("field.machine_serial", snapshot.machine_serial if snapshot else ""),
        ("field.ticket", report.ticket),
        ("field.personnel", ", ".join(report.technicians)),
    ):
        if value:
            labels.append(key)
    if report.intervention_types:
        labels.append("field.intervention_types")
        labels.extend("intervention." + kind for kind in report.intervention_types)
    if "other" in report.intervention_types:
        labels.extend(("field.other_intervention_details",
                       "metadata.other_intervention_detail"))
    if preview:
        labels.extend(("heading.report_content", "preview.summary_detail"))
        # Preview renders manual breaks as customer-visible placeholder text.
        # Traverse the canonical hierarchy, including nested modules and Conclusions.
        pending = [*report.modules, report.conclusion]
        while pending:
            module = pending.pop()
            for block in module.blocks:
                if isinstance(block, PageBreakBlock):
                    labels.append("preview.manual_page_break")
                    pending.clear()
                    break
                if isinstance(block, NestedModuleBlock):
                    pending.append(block.module)
            if "preview.manual_page_break" in labels:
                break
    if footer_note:
        labels.append("branding.footer_note")
        if preview:
            labels.append("preview.footer_prefix")
    return tuple(labels)
